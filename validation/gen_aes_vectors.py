"""Generate lean/SmcIrred/AES/Vectors{128,192,256}.lean: FIPS-197 vectors proved round by round
(AES.Chain), each kernel run small.  The Python below is only a literal generator; Lean checks every literal."""
import re
from pathlib import Path
OUT = Path(__file__).resolve().parents[1] / "lean/SmcIrred/AES"
PT = 0x00112233445566778899aabbccddeeff
def xt(a): return (((a << 1) ^ 0x1B) & 0xFF) if a & 0x80 else a << 1
def gmul(a, b):
    r = 0
    for _ in range(8):
        if b & 1: r ^= a
        a = xt(a) & 0xFF if a < 256 else xt(a); b >>= 1
    return r
def ginv(a):
    r, b = 1, a
    for e in range(8):
        if (254 >> e) & 1: r = gmul(r, b)
        b = gmul(b, b)
    return r
def rotl8(x, k): return ((x << k) | (x >> (8 - k))) & 0xFF
def sbox(x):
    b = ginv(x); return b ^ rotl8(b, 1) ^ rotl8(b, 2) ^ rotl8(b, 3) ^ rotl8(b, 4) ^ 0x63
INV = [0] * 256
for x in range(256): INV[sbox(x)] = x
isbox = lambda y: INV[y]
RCON = [0, 1, 2, 4, 8, 16, 32, 64, 128, 27, 54, 108, 216, 171, 77]
def bebytes(n, k): return [(n >> (8 * (k - 1 - j))) & 255 for j in range(k)]
def keyexp(key, Nk, Nr):
    w = [key[4 * j:4 * j + 4] for j in range(Nk)]
    for i in range(Nk, 4 * (Nr + 1)):
        t = w[i - 1]
        if i % Nk == 0:
            t = [sbox(x) for x in t[1:] + t[:1]]; t = [t[0] ^ RCON[i // Nk]] + t[1:]
        elif Nk > 6 and i % Nk == 4: t = [sbox(x) for x in t]
        w.append([a ^ b for a, b in zip(w[i - Nk], t)])
    return w
rkey = lambda w, r: [b for c in range(4) for b in w[4 * r + c]]
xor = lambda a, b: [x ^ y for x, y in zip(a, b)]
shift = lambda s: [s[(r + 4 * c + 4 * r) % 16] if False else s[4 * ((c + r) % 4) + r] for c in range(4) for r in range(4)]
ishift = lambda s: [s[4 * ((c - r) % 4) + r] for c in range(4) for r in range(4)]
def mixcol(c):
    a = c; return [gmul(2, a[0]) ^ gmul(3, a[1]) ^ a[2] ^ a[3], a[0] ^ gmul(2, a[1]) ^ gmul(3, a[2]) ^ a[3],
                   a[0] ^ a[1] ^ gmul(2, a[2]) ^ gmul(3, a[3]), gmul(3, a[0]) ^ a[1] ^ a[2] ^ gmul(2, a[3])]
def imixcol(a): return [gmul(14, a[0]) ^ gmul(11, a[1]) ^ gmul(13, a[2]) ^ gmul(9, a[3]), gmul(9, a[0]) ^ gmul(14, a[1]) ^ gmul(11, a[2]) ^ gmul(13, a[3]),
                        gmul(13, a[0]) ^ gmul(9, a[1]) ^ gmul(14, a[2]) ^ gmul(11, a[3]), gmul(11, a[0]) ^ gmul(13, a[1]) ^ gmul(9, a[2]) ^ gmul(14, a[3])]
cols = lambda f, s: [b for c in range(4) for b in f(s[4 * c:4 * c + 4])]
sub = lambda s: [sbox(x) for x in s]
isub = lambda s: [isbox(x) for x in s]
def lst(l): return "[" + ", ".join(str(x) for x in l) + "]"
def llst(ls): return "[" + ", ".join(lst(l) for l in ls) + "]"
def gen(bits, Nk, Nr, K, C, exp_last):
    n = str(bits); w = keyexp(bebytes(K, 4 * Nk), Nk, Nr)
    s = xor(bebytes(PT, 16), rkey(w, 0)); E = [s]
    for i in range(Nr - 1):
        s = xor(cols(mixcol, shift(sub(s))), rkey(w, i + 1)); E.append(s)
    out = xor(shift(sub(s)), rkey(w, Nr)); assert out == bebytes(C, 16), "encrypt mismatch"
    d = isub(ishift(xor(bebytes(C, 16), rkey(w, Nr)))); D = [d]
    for i in range(Nr - 1):
        d = isub(ishift(cols(imixcol, xor(d, rkey(w, Nr - 1 - i))))); D.append(d)
    assert xor(d, rkey(w, 0)) == bebytes(PT, 16), "decrypt mismatch"
    L = ["module", "", "public import SmcIrred.AES.VectorsBase", "public import SmcIrred.AES.Chain", "", "public section", "",
         "namespace SmcIrred.AES", "",
         f"/-! FIPS-197 Appendix C AES-{n} vector proved round by round (generated by `validation/gen_aes_vectors.py`;",
         "the literals are only intermediate states, every equation is checked by the kernel). -/", "",
         f"@[expose] def rk{n} : List (List Nat) := {llst(w)}",
         f"@[expose] def encS{n} : List (List Nat) := {llst(E)}",
         f"@[expose] def decS{n} : List (List Nat) := {llst(D)}", "",
         f"theorem aes{n}_rk : aes{n} {hex(K)} = rk{n} := by decide +kernel", ""]
    for i in range(Nr - 1):
        L.append(f"theorem enc{n}_s{i} : encStep rk{n} {i} (encS{n}.getD {i} []) = encS{n}.getD {i + 1} [] := by decide +kernel")
    for i in range(Nr - 1):
        L.append(f"theorem dec{n}_s{i} : decStep rk{n} {Nr - 1 - i} (decS{n}.getD {i} []) = decS{n}.getD {i + 1} [] := by decide +kernel")
    mt = lambda p: "\n".join([f"  match i, hi with"] + [f"  | {i}, _ => exact {p}{n}_s{i}" for i in range(Nr - 1)] + [f"  | k + {Nr - 1}, h => omega"])
    L += ["", f"theorem enc{n} : encrypt {Nr} (aes{n} {hex(K)}) (beBytes pt 16) =",
          f"    beBytes {hex(C)} 16 := by",
          f"  rw [aes{n}_rk]",
          f"  refine encrypt_chain {Nr} rk{n} _ _ encS{n} (by decide +kernel) (fun i hi => ?_) (by decide +kernel)",
          mt("enc"), "",
          f"theorem dec{n} : decrypt {Nr} (aes{n} {hex(K)})",
          f"    (beBytes {hex(C)} 16) = beBytes pt 16 := by",
          f"  rw [aes{n}_rk]",
          f"  refine decrypt_chain {Nr} rk{n} _ _ decS{n} (by decide +kernel) (fun i hi => ?_) (by decide +kernel)",
          mt("dec"), "",
          f"/-- FIPS-197 key-expansion check: the last word of the AES-{n} expansion. -/",
          f"theorem keyexp{n}_last : (aes{n} {hex(exp_last[0])}).getD {4 * (Nr + 1) - 1} [] = beBytes {hex(exp_last[1])} 4 := by",
          f"  decide +kernel", "",
          f"theorem keyexp_length{n} : (aes{n} 0).length = {4 * (Nr + 1)} := by decide +kernel", "", "end SmcIrred.AES", ""]
    (OUT / f"Vectors{n}.lean").write_text("\n".join(L), encoding="utf-8")
