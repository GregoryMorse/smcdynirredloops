"""Generate lean/Challenge.lean and lean/ChallengeAES.lean mechanically from the Spec modules (plan D6).

A Challenge is the Spec modules reachable from SmcIrred.Spec.Paper, concatenated in import order, with imports and `theorem`
blocks removed and every declaration that the selected statements do not (transitively) mention pruned, and a single theorem
`PalomarSIL.mathematical_result` whose proof is `sorry`. Two selections are generated because one Challenge may have at most
1,000 lines and 100 KiB: `Challenge` (solver, extremal numbers, transformations, security model) and `ChallengeAES` (the AES
graphs).
Usage: python validation/make_challenge.py [--check]   (--check fails when a generated file differs)."""
import re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LEAN = ROOT / "lean"
TOP = "SmcIrred.Spec.Paper"
VARIANTS = {
    "Challenge": ["SmcTwoSatCorrect", "IrreducibleExtremal", "TransformCorrect", "SecurityModel"],
    "ChallengeAES": ["CircuitCFGCorrect"],
}
DESC = {
    "SmcTwoSatCorrect": "the self-modifying-code 2-SAT solver and the planted generator (`SmcTwoSatCorrect`)",
    "IrreducibleExtremal": "the extremal numbers of irreducible loops and multiple-entry edges (`IrreducibleExtremal`)",
    "TransformCorrect": "the irreducible-loop transformations of Figures 5 and 6 (`TransformCorrect`)",
    "CircuitCFGCorrect": "the Boolean control-flow graphs of AES-128, AES-192 and AES-256 (`CircuitCFGCorrect`)",
    "SecurityModel": "the security model of Section 5.1 relative to explicit structural assumptions (`SecurityModel`)",
}


def header(roots):
    fams = "; ".join(DESC[r] for r in roots)
    return ("module\npublic section\n/-!\n"
            "# Control flow obfuscation with irreducible loops and self-modifying code: selected mathematical result\n"
            "Morse, Alqaradaghi and Kozsik, Publ. Math. Debrecen 100 (Supplementum) (2022) 617-637, DOI 10.5486/PMD.2022.Suppl.5,\n"
            "with the corrections recorded in lean/errata. The statement selects: " + fams + ". Definitions keep the\n"
            "development's names. Timings, tool experiments, literature statements and opinions of the paper, the x86-64 machine\n"
            "code and the compilers and decompilers are outside this statement; see PALOMAR_SEMANTICS.md and lean/PAPER_MAP.md.\n"
            "This file is generated by validation/make_challenge.py from lean/SmcIrred/Spec/*.lean. The single intentional\n"
            "theorem hole belongs to Challenge; Solution proves it. No custom axiom is assumed. AI-assisted development; no\n"
            "independent human review is claimed. No submission or registration has been made.\n-/\n")


def footer(roots):
    conj = " ∧ ".join("SmcIrred.Paper." + r for r in roots)
    return ("namespace PalomarSIL\n/-- " + (lambda t: t[0].upper() + t[1:])("; ".join(DESC[r] for r in roots)) + ". -/\n"
            "theorem mathematical_result : " + conj + " := by\n  sorry\nend PalomarSIL\n")


START = re.compile(r"^(/--|/-!|@\[|def\b|noncomputable def\b|structure\b|inductive\b|abbrev\b|theorem\b|lemma\b|instance\b|"
                   r"set_option\b|open\b|variable\b|private\b)")
KW = re.compile(r"^(?:@\[[^\]]*\]\s*)?(?:noncomputable\s+)?(def|structure|inductive|abbrev|theorem|lemma|instance)\s+([\w.']+)")


def path(m): return LEAN / (m.replace(".", "/") + ".lean")


def imports(m): return re.findall(r"^public import\s+(SmcIrred[\w.]*)", path(m).read_text(encoding="utf-8"), re.M)


def order(m, seen, out):
    if m in seen: return
    seen.add(m)
    for i in imports(m): order(i, seen, out)
    out.append(m)


def chunks(m):
    """[(defined name or None, kind, text)]: a docstring directly above a declaration belongs to it; namespace lines are kind ns."""
    text = path(m).read_text(encoding="utf-8").replace("\r\n", "\n").split("public section", 1)[1]
    lines = text.strip("\n").split("\n")
    out, cur = [], []
    for ln in lines:
        top = START.match(ln) or re.match(r"^(namespace|end)\b", ln)
        if top:
            if cur and re.match(r"^(def|structure|inductive|abbrev|theorem|lemma|instance|@\[|noncomputable)", ln) and \
                    "".join(cur).strip().startswith("/--") and "".join(cur).rstrip().endswith("-/"):
                cur.append(ln); continue
            if cur: out.append(cur)
            cur = [ln]
        else:
            cur.append(ln)
    if cur: out.append(cur)
    res = []
    for c in out:
        body = "\n".join(c).rstrip("\n")
        stripped = re.sub(r"^/--.*?-/\s*", "", body, flags=re.S) if body.lstrip().startswith("/--") else body
        mm = KW.match(stripped)
        kind = mm.group(1) if mm else ("ns" if re.match(r"^(namespace|end)\b", stripped) else "other")
        res.append((mm.group(2) if mm else None, kind, body))
    return res


def words(s):
    """Identifiers of the code of a chunk: docstrings and comments do not make a declaration reachable."""
    s = re.sub(r"/-.*?-/", "", s, flags=re.S)
    s = re.sub(r"--[^\n]*", "", s)
    return set(re.findall(r"[A-Za-z_][\w']*", s))


def build(name="Challenge"):
    roots = VARIANTS[name]; head = header(roots); foot = footer(roots)
    mods = []; order(TOP, set(), mods)
    allc = []
    for m in mods:
        for (n, k, b) in chunks(m):
            if k in ("theorem", "lemma"): continue
            allc.append([m, n, k, b])
    # reachability: a plain name is reached by the word itself; a dotted name `A.b` by the word `b` once `A` is reached (a
    # type or namespace mentioned in a kept declaration or kept itself), so that `g.n` does not pull in `GB.n`
    keep = set()
    wordsof = {idx: words(c[3]) for idx, c in enumerate(allc)}
    for idx, (m, n, k, b) in enumerate(allc):
        if n and n in roots and m == TOP: keep.add(idx)
    changed = True
    while changed:
        changed = False
        seen_words = set().union(*[wordsof[i] for i in keep]) if keep else set()
        seen_last = {allc[i][1].split(".")[-1] for i in keep if allc[i][1]}
        for idx, (m, n, k, b) in enumerate(allc):
            if idx in keep or not n: continue
            ps = n.split(".")
            if ps[-1] not in seen_words: continue
            if len(ps) > 1 and not (ps[-2] in seen_words or ps[-2] in seen_last): continue
            keep.add(idx); changed = True
    parts = [head]
    for m in mods:
        mine = [(i, c) for i, c in enumerate(allc) if c[0] == m]
        if not any(i in keep for i, c in mine): continue
        ns = [c[3] for i, c in mine if c[2] == "ns" and c[3].startswith("namespace")]
        ends = [c[3] for i, c in mine if c[2] == "ns" and c[3].startswith("end")]
        parts.append(f"-- ===== {m} =====")
        parts += ns
        parts.append("")
        for pos, (i, c) in enumerate(mine):
            if i in keep:
                parts.append(c[3] + "\n")
            elif c[2] == "other" and re.match(r"^(open|set_option|variable)\b", c[3]):
                # `open X in` and `set_option ... in` belong to the declaration after them; other opens, set_options and
                # variables are kept for every module that contributes a declaration
                if c[3].rstrip().endswith(" in"):
                    if pos + 1 < len(mine) and mine[pos + 1][0] in keep: parts.append(c[3] + "\n")
                else:
                    parts.append(c[3] + "\n")
        parts += ends
    parts.append(foot)
    out = "\n".join(parts)
    # an `open` of a namespace that pruning left empty is an error: keep only the namespaces the output declares
    declared = set(re.findall(r"^namespace\s+(\S+)", out, re.M))

    def fix_open(mo):
        ns = [t for t in mo.group(1).split()
              if not t.startswith("SmcIrred") or any(d == t or d.startswith(t + ".") for d in declared)]
        return ("open " + " ".join(ns)) if ns else ""
    out = re.sub(r"^open ((?:[\w.]+ ?)+)$", fix_open, out, flags=re.M)
    m = re.search(r".{0,40}\b(axiom|native_decide|unsafe|implemented_by)\b.{0,40}", out.replace(head, ""))
    assert not m, "forbidden token in Challenge: " + m.group(0)
    return out


if __name__ == "__main__":
    bad = False
    for name in VARIANTS:
        new = build(name); out = LEAN / (name + ".lean")
        if "--check" in sys.argv:
            old = out.read_text(encoding="utf-8") if out.exists() else ""
            if old.replace("\r\n", "\n") != new: print(name + ".lean is out of date"); bad = True
            else: print(name + ".lean up to date")
            continue
        out.write_text(new, encoding="utf-8", newline="\n")
        print(f"wrote {out}: {new.count(chr(10))} lines, {len(new.encode('utf-8'))} bytes")
    sys.exit(1 if bad else 0)
