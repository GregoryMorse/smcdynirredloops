"""Generate lean/SmcIrred/Data/ProtectedSpecs.lean from the planted formulas that native/protected.c generates for seeds 1..8
(plan R19b, evidence D12): python validation/protected_vectors.py [--exe PATH] [--check].
The Lean file states, for every seed, that the implications printed by the C program are exactly `genForest sigma specs`
followed by implications that respect sigma (so the generated formula is planted, `Gen.Construct.genForest_planted`) and that
the static scheme theorem applies. The program run is mechanical evidence about the C generator; the proofs are in Lean."""
import argparse, subprocess, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "lean/SmcIrred/Data/ProtectedSpecs.lean"
SEEDS = list(range(1, 9))


def dump(exe: Path, seed: int):
    t = subprocess.run([str(exe), "--dump", str(seed)], capture_output=True, text=True, check=True).stdout.splitlines()
    d = {"specs": [], "imps": []}
    for line in t:
        w = line.split()
        if w[0] == "seed": d["n"] = int(w[3])
        elif w[0] == "sigma": d["sigma"] = [int(x) for x in w[1:]]
        elif w[0] == "req": d["req"] = [int(x) for x in w[1:]]
        elif w[0] == "spec": d["specs"].append((int(w[1]), [int(x) for x in w[2:]]))
        elif w[0] == "imp": d["imps"].append(tuple(int(x) for x in w[1:5]))
        elif w[0] == "sat": d["sat"] = int(w[1])
        elif w[0] == "out": d["out"] = [int(x) for x in w[1:]]
    return d


def lean(seed: int, d: dict) -> str:
    n = d["n"]
    sig = ", ".join("true" if b else "false" for b in d["sigma"])
    specs = ", ".join(f"({x}, [{', '.join(map(str, ms))}])" for x, ms in d["specs"])
    chain_edges = sum(len(ms) + 1 for _, ms in d["specs"])
    imps = d["imps"]
    lit = lambda p, v: f"⟨{p}, {'true' if v else 'false'}⟩"
    allimps = ",\n    ".join(f"({lit(a, va)}, {lit(b, vb)})" for a, va, b, vb in imps)
    extras = ",\n    ".join(f"({lit(a, va)}, {lit(b, vb)})" for a, va, b, vb in imps[chain_edges:])
    ms1 = '[' + ', '.join(map(str, next(ms for x, ms in d['specs'] if x == 1))) + ']'
    ms2 = '[' + ', '.join(map(str, next(ms for x, ms in d['specs'] if x == 2))) + ']'
    s = f"""
/-! Seed {seed}: n = {n}, {len(d['specs'])} forcing chains, {len(imps)} implications; the C solver reports sat = {d['sat']}. -/

@[expose] def sigma{seed} : Nat → Bool := fun k => [{sig}].getD k false

@[expose] def specs{seed} : List (Nat × List Nat) := [{specs}]

@[expose] def extras{seed} : List (Lit × Lit) := [{extras}]

/-- The implications printed by the C generator for seed {seed}. -/
@[expose] def imps{seed} : List (Lit × Lit) := [{allimps}]

/-- Literal transcription: the C formula is the forest of the chains followed by the extra implications. -/
theorem imps{seed}_eq : imps{seed} = genForest sigma{seed} specs{seed} ++ genExtra {n} sigma{seed} extras{seed} := by rfl

/-- Every extra implication respects the planted assignment and stays among the variables (none is dropped by `genExtra`). -/
theorem extras{seed}_kept : genExtra {n} sigma{seed} extras{seed} = extras{seed} := by rfl

theorem seed{seed}_scheme {{S T : Lang.Stmt}} (hS : Lang.Structured S) (hT : Lang.Structured T) (hS1 : 1 ≤ S.size) :
    ∃ sol, smcSolve (impFormula {n} imps{seed}) = some sol ∧
      (let o : Nat → Bool := fun k => decide (2 * k ∈ sol)
       o 1 = false ∧ o 2 = false ∧
       ∀ (env v : Bool) (r : List Nat × Bool),
         ((∃ f, Lang.exec f (Lang.compile (.seq S T)) o env 0 v [] = some r) ↔
           ∃ f, Lang.exec f (Lang.compile (Lang.prot5 S T)) o env 0 v [] = some r)) ∧
      (Lang.cfgOf (Lang.compile (.seq S T))).Reducible 0 ∧
      (∀ {{J : Jungle}}, J.Valid (Lang.cfgOf (Lang.compile (Lang.prot5 S T))) 0 →
        ∃ w, (Lang.cfgOf (Lang.compile (Lang.prot5 S T))).Irreducible J w) := by
  rw [imps{seed}_eq]
  exact generated_scheme (σ := sigma{seed}) (specs := specs{seed}) (cands := extras{seed})
    (by decide) (by decide) (by decide) ⟨{ms1}, by decide⟩ ⟨{ms2}, by decide⟩ (by decide) (by decide) hS hT hS1
"""
    return s


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--exe", default=str(ROOT / "validation/.build/native/protected_x64.exe"))
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    head = """module

public import SmcIrred.Gen.Construct

public section

namespace SmcIrred

/-! GENERATED by validation/protected_vectors.py from the output of `native/protected.c --dump SEED` (plan R19b). Do not edit.
Mechanical evidence (D12): the implications of the planted formulas the C generator produces for seeds 1-8 are an instance of
`genForest` followed by implications that respect the planted assignment; `Gen.Construct.generated_scheme` then applies. -/
"""
    text = head + "".join(lean(s, dump(Path(a.exe), s)) for s in SEEDS) + "\nend SmcIrred\n"
    if a.check:
        ok = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print("up to date" if ok else "OUT OF DATE")
        return 0 if ok else 1
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print("wrote", OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
